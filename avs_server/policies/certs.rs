use anyhow::Context;
use glob::glob;
use x509_cert::der::Encode;
use x509_cert::Certificate;

/// Extracts the SubjectPublicKeyInfo (SPKI) DER-encoded bytes for every
/// certificate present in a PEM-encoded certificate string, in order.
pub fn extract_spki_from_pem(pem: &str) -> anyhow::Result<Vec<Vec<u8>>> {
    let certs = Certificate::load_pem_chain(pem.as_bytes())
        .map_err(|e| anyhow::anyhow!("failed to parse PEM certificate chain: {e}"))?;
    if certs.is_empty() {
        anyhow::bail!("no certificates found in PEM");
    }

    certs
        .into_iter()
        .map(|cert| {
            cert.tbs_certificate
                .subject_public_key_info
                .to_der()
                .map_err(|e| anyhow::anyhow!("failed to serialize public key to DER: {e}"))
        })
        .collect()
}

/// Loads all certificates matching the specified glob pattern.
/// Returns a vector of strings, each containing the content of a certificate
/// file.
pub fn load_certificates(glob_pattern: &str) -> anyhow::Result<Vec<String>> {
    let mut certs = Vec::new();

    for entry in glob(glob_pattern).context("Failed to parse certificate glob pattern")? {
        let path = entry.context("Failed to resolve glob entry")?;
        if path.is_file() {
            let content = std::fs::read_to_string(&path)
                .with_context(|| format!("Failed to read certificate file {:?}", path))?;
            certs.push(content);
        }
    }
    Ok(certs)
}

