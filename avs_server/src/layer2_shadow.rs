    #[test]
    fn test_extract_identity_from_endorsement() {
        use oak_proto_rust::oak::attestation::v1::Endorsement;

        // 1. Full statement with subject and workload
        let statement = serde_json::json!({
            "subject": [{"name": "mpm_test_subject"}],
            "predicate": {
                "claims": [{
                    "type": "https://example.com/claims/workload.md",
                    "annotations": {
                        "workload_id": "test-workload-1"
                    }
                }]
            }
        });
        let signed = SignedEndorsement {
            endorsement: Some(Endorsement {
                serialized: serde_json::to_vec(&statement).unwrap(),
                ..Default::default()
            }),
            ..Default::default()
        };
        let (sub, wl) = extract_identity_from_endorsement(&signed);
        assert_eq!(sub, "mpm_test_subject");
        assert_eq!(wl, "test-workload-1");

        // 2. Empty or missing endorsement
        let empty = SignedEndorsement::default();
        let (sub, wl) = extract_identity_from_endorsement(&empty);
        assert_eq!(sub, "none");
        assert_eq!(wl, "none");

        // 3. Subject only, no workload claim
        let no_wl_statement = serde_json::json!({
            "subject": [{"name": "mpm_test_subject"}],
            "predicate": {
                "claims": [{
                    "type": "https://example.com/claims/other.md"
                }]
            }
        });
        let signed_no_wl = SignedEndorsement {
            endorsement: Some(Endorsement {
                serialized: serde_json::to_vec(&no_wl_statement).unwrap(),
                ..Default::default()
            }),
            ..Default::default()
        };
        let (sub, wl) = extract_identity_from_endorsement(&signed_no_wl);
        assert_eq!(sub, "mpm_test_subject");
        assert_eq!(wl, "none");
    }

    #[test]
    fn test_run_shadow_matrix_evaluation() {
        let current_ref = CbLayer2TransparentReferenceValues {
            binary_mpms: vec![versions_ref_value("pkg_a/1.0"), versions_ref_value("pkg_b/2.0")],
            ..Default::default()
        };
        let current_policy = TransparentLayer2Policy::new(&current_ref);

        let cand_ref = CbLayer2TransparentReferenceValues {
            binary_mpms: vec![versions_ref_value("pkg_a/1.0")],
            ..Default::default()
        };
        let candidate = CandidatePolicy::new(&cand_ref);

        let evidence = layer2_evidence(&["pkg_a/1.0", "pkg_unverified/3.0"]);

        let inputs = ShadowInputs {
            current: &current_policy,
            current_ref: &current_ref,
            candidate: Some(&candidate),
            policy_name: "test_policy",
            operator_role: "test_role",
            enforced_ok: true,
            enforced_outcome: None,
        };

        let report = run_shadow(&inputs, TEST_TIME, &evidence, &Variant::default());
        let matrix = report.matrix_sample.expect("matrix_sample must be populated");
        // 2 packages * 2 sources (current, candidate) = 4 entries
        assert_eq!(matrix.len(), 4);

        // pkg_a vs current: accepted in slot 0
        let pkg_a_curr = &matrix[0];
        assert_eq!(pkg_a_curr.index, 0);
        assert_eq!(pkg_a_curr.ref_source, "current");
        assert_eq!(pkg_a_curr.accepted_slots, vec![0]);
        // With empty endorsement, extract_identity returns "none"
        assert_eq!(pkg_a_curr.subject_name, "none");
        assert_eq!(pkg_a_curr.workload_id, "none");

        // pkg_a vs candidate: accepted in slot 0
        let pkg_a_cand = &matrix[1];
        assert_eq!(pkg_a_cand.index, 0);
        assert_eq!(pkg_a_cand.ref_source, "candidate");
        assert_eq!(pkg_a_cand.candidate_id, candidate.candidate_id);
        assert_eq!(pkg_a_cand.accepted_slots, vec![0]);

        // pkg_unverified vs current: accepted in no slots -> "unverified"
        let pkg_unv_curr = &matrix[2];
        assert_eq!(pkg_unv_curr.index, 1);
        assert_eq!(pkg_unv_curr.ref_source, "current");
        assert!(pkg_unv_curr.accepted_slots.is_empty());
        assert_eq!(pkg_unv_curr.subject_name, "unverified");
        assert_eq!(pkg_unv_curr.workload_id, "unverified");

        // pkg_unverified vs candidate: accepted in no slots -> "unverified"
        let pkg_unv_cand = &matrix[3];
        assert_eq!(pkg_unv_cand.index, 1);
        assert_eq!(pkg_unv_cand.ref_source, "candidate");
        assert!(pkg_unv_cand.accepted_slots.is_empty());
        assert_eq!(pkg_unv_cand.subject_name, "unverified");
        assert_eq!(pkg_unv_cand.workload_id, "unverified");
    }

